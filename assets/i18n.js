  var LANGS = [["zh", "中文"], ["en", "English"], ["ja", "日本語"], ["ko", "한국어"]];

  function validLang(l) {
    for (var i = 0; i < LANGS.length; i++) if (LANGS[i][0] === l) return true;
    return false;
  }

  function current() {
    var l = null;
    try { l = localStorage.getItem("fp_lang"); } catch (e) {}
    return validLang(l) ? l : "zh";
  }

  function t(key, lang) {
    lang = lang || current();
    var d = ui[lang] || {};
    var v = d[key];
    if (v == null) v = (ui.zh || {})[key];
    return v == null ? key : v;
  }

  function fmt(str, vars) {
    if (str == null) return "";
    return String(str).replace(/\{(\w+)\}/g, function (m, k) {
      return (vars && vars[k] != null) ? vars[k] : m;
    });
  }

  function set(lang) {
    if (!validLang(lang)) lang = "zh";
    try { localStorage.setItem("fp_lang", lang); } catch (e) {}
    apply(lang);
  }

  function apply(lang) {
    lang = validLang(lang) ? lang : current();
    document.documentElement.lang = (lang === "zh" ? "zh-CN" : lang);

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      if (el.hasAttribute("data-i18n-attr")) return;
      var v = t(el.getAttribute("data-i18n"), lang);
      if (typeof v === "string") el.textContent = v;
    });

    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
      var attr = el.getAttribute("data-i18n-attr");
      var key = el.getAttribute("data-i18n");
      if (!attr || !key) return;
      var v = t(key, lang);
      if (typeof v === "string") el.setAttribute(attr, v);
    });

    var sel = document.getElementById("langsel");
    if (sel) sel.value = lang;

    if (typeof window.renderPortal === "function") window.renderPortal();
    if (typeof window.renderViewer === "function") window.renderViewer();

    try {
      document.dispatchEvent(new CustomEvent("i18n:change", { detail: { lang: lang } }));
    } catch (e) {}
  }

